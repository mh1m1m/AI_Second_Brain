#!/usr/bin/env python3
"""Mirror backlog tickets to GitHub Issues. `backlog/backlog.json` is the only place a ticket may be changed.

    python tools/github_mirror.py OWNER/REPO                    push tickets that changed in the backlog
    python tools/github_mirror.py OWNER/REPO --check            compare GitHub with the last push; change nothing
    python tools/github_mirror.py OWNER/REPO --accept-backlog   push, overwriting issues that were edited on GitHub
    python tools/github_mirror.py --pending                     offline: tickets changed since the last push
    python tools/github_mirror.py OWNER/REPO --dry-run

The mirror is one-way, and divergence is never silent:

- `backlog/github-issues.json` records, for each ticket, its issue number and a fingerprint of what was last pushed
  (title, open or closed, managed labels, milestone, body).
- Every pushed body ends with a hidden marker holding the same fingerprint. An issue whose live content no longer
  matches its own marker was edited on GitHub. `--check` reports it and exits 1. A push refuses to overwrite it
  unless `--accept-backlog` is given, which is the reconciliation step: decide, make the change in `backlog.json`
  if it was right, then push with `--accept-backlog`.
- An issue that matches its own marker but not this checkout's record was pushed by the mirror from another branch.
  That is reported as a note, not as drift, and the next push from this checkout replaces it.
- A ticket whose expected fingerprint differs from the recorded one has not been pushed yet. `--pending` reports it
  without the network; the test suite runs the same comparison, so CI fails when a push was forgotten.

This detects accidental divergence. It is not a security boundary: whoever can edit an issue can rewrite its marker.

Comments on issues are not mirrored and are free for discussion. Issues whose title does not start with a ticket
identifier (review findings, for example) are ignored. Uses the `gh` CLI's REST interface. Project tooling, not part
of the service.
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
import time

import backlog

MAP = backlog.ROOT / "backlog" / "github-issues.json"
COLOURS = {"type": "1d76db", "priority": "b60205", "wave": "5319e7", "status": "0e8a16", "gate": "d93f0b", "review": "fbca04"}
TICKET_TITLE = re.compile(r"SB-\d{3}\b")
FIELDS = ("title", "state", "labels", "milestone", "body")
MARKER = re.compile(r"\n?<!-- mirror:([0-9a-f]{64}) -->\s*\Z")
SESSION_FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def labels_for(t: dict) -> list[str]:
    out = [f"type: {t['type']}", f"priority: {t['priority']}", f"wave: {t['wave']}", f"status: {t['status'].lower()}"]
    if t.get("gate"):
        out.append(f"gate: {t['gate']}")
    if t.get("security_relevant"):
        out.append("review: security")
    return out


def managed(label: str) -> bool:
    return label.split(":")[0] in COLOURS and ":" in label


def payload(t: dict, milestone: int | None, pages: dict[str, str]) -> dict:
    body = pages[f"backlog/tickets/{t['id']}.md"].split("\n", 2)[2]
    body += "\n---\nMirrored from `backlog/backlog.json`. Change the ticket there, not here: edits made on GitHub are reported as drift and overwritten."
    out = {"title": f"{t['id']} {t['title']}", "body": body, "labels": labels_for(t), "state": "closed" if t["status"] == "DONE" else "open"}
    stamp = fingerprint(view(out["title"], out["state"], out["labels"], f"Wave {t['wave']}", body))
    out["body"] = f"{body}\n<!-- mirror:{stamp} -->"
    if milestone is not None:
        out["milestone"] = milestone
    return out


def view(title: str, state: str, labels: list[str], milestone: str, body: str) -> dict:
    """The fields the mirror owns, in one comparable form."""
    text = "\n".join(line.rstrip() for line in (body or "").replace("\r\n", "\n").strip().split("\n"))
    if text.endswith(SESSION_FOOTER):  # appended by the session's GitHub proxy, not by this tool and not by a person
        text = text[: -len(SESSION_FOOTER)].rstrip()
    text = MARKER.sub("", text).rstrip()
    return {"title": title.strip(), "state": state, "labels": sorted(x for x in labels if managed(x)), "milestone": milestone, "body": text}


def expected_view(t: dict, pages: dict[str, str]) -> dict:
    p = payload(t, None, pages)
    return view(p["title"], p["state"], p["labels"], f"Wave {t['wave']}", p["body"])


def marker(body: str) -> str:
    """The fingerprint the mirror wrote into the body, or an empty string."""
    text = (body or "").replace("\r\n", "\n").strip()
    if text.endswith(SESSION_FOOTER):
        text = text[: -len(SESSION_FOOTER)].rstrip()
    found = MARKER.search(text)
    return found.group(1) if found else ""


def live_view(issue: dict) -> dict:
    return view(issue["title"], issue["state"], [x["name"] for x in issue["labels"]], (issue.get("milestone") or {}).get("title", ""), issue.get("body") or "")


def fingerprint(v: dict) -> str:
    return hashlib.sha256(json.dumps(v, ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()


def differing(a: dict, b: dict) -> list[str]:
    return [f for f in FIELDS if a[f] != b[f]]


def load_map() -> dict[str, dict]:
    raw = json.loads(MAP.read_text(encoding="utf-8")) if MAP.exists() else {}
    return {k: v if isinstance(v, dict) else {"issue": v, "pushed": ""} for k, v in raw.items()}


def save_map(mapping: dict[str, dict]) -> None:
    MAP.write_text(json.dumps(dict(sorted(mapping.items())), indent=1) + "\n", encoding="utf-8")


def pending(data: dict, pages: dict[str, str], mapping: dict[str, dict]) -> list[str]:
    """Tickets whose current content has not been pushed. Needs no network."""
    out = [t["id"] for t in data["tickets"] if mapping.get(t["id"], {}).get("pushed") != fingerprint(expected_view(t, pages))]
    return out + [f"{k} (no longer in the backlog)" for k in mapping if k not in {t["id"] for t in data["tickets"]}]


def elsewhere(data: dict, mapping: dict[str, dict], issues: list[dict]) -> list[str]:
    """Tickets whose issue is intact but was pushed from another state of the backlog (another branch)."""
    by_number = {i["number"]: i for i in issues if "pull_request" not in i}
    out = []
    for t in data["tickets"]:
        issue = by_number.get(mapping.get(t["id"], {}).get("issue"))
        if issue is not None:
            fp = fingerprint(live_view(issue))
            if fp != mapping[t["id"]]["pushed"] and fp == marker(issue.get("body") or ""):
                out.append(t["id"])
    return out


def drift(data: dict, pages: dict[str, str], mapping: dict[str, dict], issues: list[dict]) -> list[str]:
    """Edits made on GitHub. An empty list means every mirrored issue is exactly what the mirror wrote."""
    by_number = {i["number"]: i for i in issues if "pull_request" not in i}
    known = {m["issue"] for m in mapping.values()}
    report: list[str] = []
    for t in data["tickets"]:
        entry = mapping.get(t["id"])
        if entry is None:
            continue
        issue = by_number.get(entry["issue"])
        if issue is None:
            report.append(f"{t['id']}: issue #{entry['issue']} is missing on GitHub")
            continue
        live = live_view(issue)
        if entry["pushed"] and fingerprint(live) not in (entry["pushed"], marker(issue.get("body") or "")):
            fields = differing(live, expected_view(t, pages)) or ["content differs from what the mirror wrote"]
            report.append(f"{t['id']}: issue #{entry['issue']} was changed on GitHub ({', '.join(fields)})")
    for number, issue in sorted(by_number.items()):
        if number not in known and TICKET_TITLE.match(issue["title"]):
            report.append(f"issue #{number} '{issue['title']}' looks like a ticket but is not in the backlog")
    return report


def api(method: str, path: str, data: dict | None = None) -> dict | list:
    cmd = ["gh", "api", "-X", method, path]
    if data is not None:
        cmd += ["--input", "-"]
    # Arguments are a fixed list (no shell); `path` comes from this tool, not from user input.
    res = subprocess.run(cmd, input=json.dumps(data) if data is not None else None, capture_output=True, text=True, check=False)  # noqa: S603
    if res.returncode != 0:
        raise RuntimeError(f"{method} {path}: {res.stdout[:200]} {res.stderr[:200]}")
    return json.loads(res.stdout) if res.stdout.strip() else {}


def all_issues(repo: str) -> list[dict]:
    out: list[dict] = []
    for page in range(1, 20):
        batch = api("GET", f"repos/{repo}/issues?state=all&per_page=100&page={page}")
        out += batch
        if len(batch) < 100:
            break
    return out


def main(argv: list[str]) -> int:
    flags = {a for a in argv[1:] if a.startswith("--")}
    repo = next((a for a in argv[1:] if not a.startswith("--")), "")
    data = backlog.load()
    pages = backlog.render(data)
    mapping = load_map()
    if "--pending" in flags:
        todo = pending(data, pages, mapping)
        print("not pushed: " + ", ".join(todo) if todo else "every ticket has been pushed")
        return 1 if todo else 0
    if not repo:
        print(__doc__)
        return 2
    wanted = sorted({lab for t in data["tickets"] for lab in labels_for(t)} | {f"status: {s.lower()}" for s in backlog.STATUSES})
    if "--dry-run" in flags:
        print(f"would ensure {len(wanted)} labels, {len({t['wave'] for t in data['tickets']})} milestones; {len(pending(data, pages, mapping))} of {len(data['tickets'])} tickets to push")
        return 0
    issues = all_issues(repo)
    found = drift(data, pages, mapping, issues)
    if "--check" in flags:
        todo = pending(data, pages, mapping)
        print("\n".join(found) if found else "no drift: every mirrored issue is what the mirror wrote")
        other = elsewhere(data, mapping, issues)
        if other:
            print(f"note: {len(other)} issues were pushed from another branch; the next push from this checkout replaces them")
        print("not pushed: " + ", ".join(todo) if todo else "every ticket has been pushed")
        return 1 if found or todo else 0
    if found and "--accept-backlog" not in flags:
        print("\n".join(found))
        print("Refusing to overwrite. Decide each case, change backlog.json if the GitHub edit was right, then re-run with --accept-backlog.")
        return 1
    have = {x["name"] for x in api("GET", f"repos/{repo}/labels?per_page=100")}
    for lab in wanted:
        if lab not in have:
            api("POST", f"repos/{repo}/labels", {"name": lab, "color": COLOURS[lab.split(":")[0]]})
    stones = {m["title"]: m["number"] for m in api("GET", f"repos/{repo}/milestones?state=all&per_page=100")}
    for wave in sorted({t["wave"] for t in data["tickets"]}):
        if f"Wave {wave}" not in stones:
            stones[f"Wave {wave}"] = api("POST", f"repos/{repo}/milestones", {"title": f"Wave {wave}"})["number"]
    live = {i["number"]: fingerprint(live_view(i)) for i in issues if "pull_request" not in i}
    stamped = {i["number"]: marker(i.get("body") or "") for i in issues if "pull_request" not in i}
    pushed = 0
    for t in data["tickets"]:
        body = payload(t, stones[f"Wave {t['wave']}"], pages)
        want = fingerprint(expected_view(t, pages))
        entry = mapping.get(t["id"])
        if entry is None:
            created = api("POST", f"repos/{repo}/issues", {k: v for k, v in body.items() if k != "state"})
            entry = mapping[t["id"]] = {"issue": created["number"], "pushed": ""}
            save_map(mapping)
            if body["state"] == "closed":
                api("PATCH", f"repos/{repo}/issues/{created['number']}", {"state": "closed"})
            time.sleep(1)
        elif live.get(entry["issue"]) != want or stamped.get(entry["issue"]) != want:
            api("PATCH", f"repos/{repo}/issues/{entry['issue']}", body)
        else:
            entry["pushed"] = want
            continue
        entry["pushed"] = want
        pushed += 1
        save_map(mapping)
    save_map(mapping)
    print(f"pushed {pushed} of {len(data['tickets'])} tickets to {repo}" + (f"; overwrote {len(found)} edited on GitHub" if found else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
